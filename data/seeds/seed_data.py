async def main():
    """初始化种子数据。

    流程:
    1. 依次摄入 5 份制造文档
    2. 构建索引
    3. 输出统计
    """
    setup_logging()
    logger.info("开始初始化种子数据...")

    success = 0
    for i, doc in enumerate(SEED_DOCUMENTS, 1):
        try:
            result = await standard_ingest(doc)
            if result.status == "done":
                success += 1
                logger.info(f"  [{i}/{len(SEED_DOCUMENTS)}] ✅ {doc.title}: {result.chunk_count} chunks")
            else:
                logger.error(f"  [{i}/{len(SEED_DOCUMENTS)}] ❌ {doc.title}: {result.status} - {result.error}")
        except Exception as e:
            logger.error(f"  [{i}/{len(SEED_DOCUMENTS)}] ❌ {doc.title}: {e}")

    logger.info(f"种子数据初始化完成: {success}/{len(SEED_DOCUMENTS)} 成功")


if __name__ == "__main__":
    asyncio.run(main())
